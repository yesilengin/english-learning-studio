// Get translation from embedded dictionary or online API
export async function getTranslation(word, sentence = '') {
  const cleanWord = word.toLowerCase().replace(/[^\w]/g, '');
  
  // First, check embedded dictionary
  if (embeddedDictionary[cleanWord]) {
    return {
      word: cleanWord,
      translation: embeddedDictionary[cleanWord],
      source: 'offline',
      example: sentence
    };
  }

  // If online, try to fetch from API
  if (navigator.onLine) {
    try {
      // Use Free Dictionary API
      const response = await fetch(`https://api.dictionaryapi.dev/api/v2/entries/en/${cleanWord}`);
      if (response.ok) {
        const data = await response.json();
        if (data && data.length > 0) {
          const meanings = data[0].meanings;
          if (meanings && meanings.length > 0) {
            const definition = meanings[0].definitions[0].definition;
            return {
              word: cleanWord,
              translation: definition,
              source: 'online',
              example: sentence
            };
          }
        }
      }
    } catch (error) {
      console.error('Error fetching translation:', error);
    }
  }

  // Return null if not found
  return {
    word: cleanWord,
    translation: '',
    source: 'none',
    example: sentence
  };
}
